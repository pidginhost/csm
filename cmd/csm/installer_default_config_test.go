// `csm install` and the packages must start a host from the same config file.
// A separate installer copy drifted: keys, comments and defaults that the
// packaged file carried were missing on hosts installed by the CLI. Only the
// generated credentials may differ.
func TestInstallerWritesThePackagedConfig(t *testing.T) {
	path := filepath.Join(t.TempDir(), "csm.yaml")
	if err := deployDefaultConfig(path); err != nil {
		t.Fatalf("deployDefaultConfig: %v", err)
	}
	written, err := os.ReadFile(path) // #nosec G304 -- test-owned temp path
	if err != nil {
		t.Fatal(err)
	}
	packaged, err := os.ReadFile(filepath.Join("..", "..", "build", "packaging", "csm.yaml.default"))
	if err != nil {
		t.Fatal(err)
	}
	cfg, err := config.LoadBytes(written)
	if err != nil {
		t.Fatal(err)
	}
	if !regexp.MustCompile(`^[0-9a-f]{64}$`).MatchString(cfg.WebUI.AuthToken) {
		t.Fatal("installed config carries no generated WebUI token")
	}
	if _, parseErr := time.Parse(time.RFC3339, cfg.WebUI.AuthTokenIssuedAt); parseErr != nil {
		t.Fatal("installed config does not record the token issue time")
	}
	info, err := os.Stat(path)
	if err != nil {
		t.Fatal(err)
	}
	if info.Mode().Perm() != 0600 {
		t.Fatalf("installed config mode = %04o, want 0600", info.Mode().Perm())
	}

	normalize := func(b []byte) string {
		var out []string
		for _, line := range strings.Split(string(b), "\n") {
			trimmed := strings.TrimSpace(line)
			if strings.HasPrefix(trimmed, "auth_token:") || strings.HasPrefix(trimmed, "auth_token_issued_at:") {
				continue
			}
			out = append(out, line)
		}
		return strings.Join(out, "\n")
	}
	if normalize(written) != normalize(packaged) {
		t.Fatal("installed config differs from the packaged template beyond the generated credentials")
	}
}

// Comments and quoting in the shared template must not redirect credential
// generation away from the active WebUI fields.
func TestInstallerFillsWebUICredentialsByYAMLPath(t *testing.T) {
	original := packaging.DefaultConfig
	t.Cleanup(func() { packaging.DefaultConfig = original })
	for _, tc := range []struct {
		name string
		from string
		to   string
	}{
		{"comment", `# auto-generated on install`, `# generated by the installer`},
		{"single quotes", `auth_token: ""`, `auth_token: ''`},
		{"commented token example", "webui:\n", "# auth_token: \"\"  # auto-generated on install\nwebui:\n"},
		{"commented issue time example", "webui:\n", "# auth_token_issued_at: \"\"\nwebui:\n"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			packaging.DefaultConfig = []byte(strings.Replace(string(original), tc.from, tc.to, 1))
			path := filepath.Join(t.TempDir(), "csm.yaml")
			if err := deployDefaultConfig(path); err != nil {
				t.Fatal(err)
			}
			cfg, err := config.Load(path)
			if err != nil {
				t.Fatal(err)
			}
			if !regexp.MustCompile(`^[0-9a-f]{64}$`).MatchString(cfg.WebUI.AuthToken) {
				t.Fatal("active WebUI token was not generated")
			}
			if _, parseErr := time.Parse(time.RFC3339, cfg.WebUI.AuthTokenIssuedAt); parseErr != nil {
				t.Fatal("active WebUI token issue time was not recorded")
			}
		})
	}
}

func TestInstallerRejectsInvalidDefaultConfigBeforeWriting(t *testing.T) {
	original := packaging.DefaultConfig
	t.Cleanup(func() { packaging.DefaultConfig = original })
	for _, tc := range []struct {
		name     string
		template string
	}{
		{"malformed", string(original) + "invalid: [\n"},
		{"duplicate token", strings.Replace(string(original), "webui:\n", "webui:\n  auth_token: \"\"\n", 1)},
		{"missing webui", strings.Replace(string(original), "webui:\n", "other:\n", 1)},
	} {
		t.Run(tc.name, func(t *testing.T) {
			packaging.DefaultConfig = []byte(tc.template)
			path := filepath.Join(t.TempDir(), "csm.yaml")
			before := []byte("hostname: SET_HOSTNAME_HERE\n")
			if err := os.WriteFile(path, before, 0600); err != nil {
				t.Fatal(err)
			}
			if err := deployDefaultConfig(path); err == nil {
				t.Error("invalid template accepted")
			}
			after, err := os.ReadFile(path)
			if err != nil {
				t.Fatal(err)
			}
			if !bytes.Equal(before, after) {
				t.Error("invalid template replaced the existing config")
			}
		})
	}
}
